def normalize_url(raw_url: str) -> str:
    """Strip the fragment from a URL so #anchors don't create duplicate pages."""
    defragged, _ = urldefrag(raw_url)
    return defragged.rstrip("/")   # also strip trailing slash for consistency


def is_uci_subdomain(hostname: str) -> bool:
    """Return True if hostname is *.uci.edu (including uci.edu itself)."""
    return hostname == "uci.edu" or hostname.endswith(".uci.edu")


