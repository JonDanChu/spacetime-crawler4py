def load_site_data(jsonl_path: str) -> list[dict]:
    """Parse every line of the JSONL file into a list of dicts."""
    records = []
    with open(jsonl_path, "r", encoding="utf-8") as fh:
        for lineno, line in enumerate(fh, 1):
            line = line.strip()
            if not line:
                continue
            try:
                records.append(json.loads(line))
            except json.JSONDecodeError as exc:
                print(f"[warning] Skipping malformed JSON on line {lineno}: {exc}", file=sys.stderr)
    return records


def load_word_frequencies(dbm_path: str) -> dict[str, int]:
    """Read all key/value pairs from the DBM file."""
    with dbm.open(dbm_path, "r") as db:
        return {key.decode(): int(db[key].decode()) for key in db.keys()}


