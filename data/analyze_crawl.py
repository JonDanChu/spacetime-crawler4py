def main() -> None:
    if len(sys.argv) != 3:
        print("Usage: python3 analyze_crawl.py <site_data.jsonl> <word_frequencies.dbm>")
        sys.exit(1)

    jsonl_path, dbm_path = sys.argv[1], sys.argv[2]

    # ---- Load data --------------------------------------------------------
    print(f"Loading site data from:       {jsonl_path}")
    records = load_site_data(jsonl_path)
    print(f"  → {len(records):,} raw records loaded")

    print(f"Loading word frequencies from: {dbm_path}")
    word_freq = load_word_frequencies(dbm_path)
    print(f"  → {len(word_freq):,} unique words loaded")

    stop_words = get_stop_words()

    # ---- Q1 ---------------------------------------------------------------
    section("Q1 — Unique Pages")
    unique_count, unique_urls = q1_unique_pages(records)
    print(f"  Total unique pages (by URL, fragment ignored): {unique_count:,}")

    # ---- Q2 ---------------------------------------------------------------
    section("Q2 — Longest Page (by Word Count)")
    longest_url, longest_count = q2_longest_page(records)
    print(f"  URL:        {longest_url}")
    print(f"  Word count: {longest_count:,}")

    # ---- Q3 ---------------------------------------------------------------
    section("Q3 — Top 50 Words (stop words excluded)")
    top50 = q3_top50_words(word_freq, stop_words)
    col_w = max((len(w) for w, _ in top50), default=10) + 2
    print(f"  {'Rank':<6} {'Word':<{col_w}} {'Frequency':>12}")
    print(f"  {'-'*6} {'-'*col_w} {'-'*12}")
    for rank, (word, freq) in enumerate(top50, 1):
        print(f"  {rank:<6} {word:<{col_w}} {freq:>12,}")

    # ---- Q4 ---------------------------------------------------------------
    section("Q4 — UCI.edu Subdomains (alphabetical)")
    subdomains = q4_uci_subdomains(unique_urls)
    print(f"  Total subdomains found: {len(subdomains):,}\n")
    for sub, count in subdomains:
        print(f"  {sub}, {count}")

    print()


if __name__ == "__main__":
    main()