def q1_unique_pages(records: list[dict]) -> tuple[int, set[str]]:
    """
    Q1 – How many unique pages?
    Uniqueness is defined by the URL *after* stripping the fragment.
    Returns (count, set_of_unique_normalized_urls).
    """
    seen: set[str] = set()
    for rec in records:
        seen.add(normalize_url(rec["url"]))
    return len(seen), seen


def q2_longest_page(records: list[dict]) -> tuple[str, int]:
    """
    Q2 – Which page has the most words?
    When the same normalized URL appears multiple times, use the max word count
    (e.g. a re-crawl that captured more content).
    Returns (url, word_count).
    """
    best_url = ""
    best_count = -1
    seen: dict[str, int] = {}
    for rec in records:
        url = normalize_url(rec["url"])
        count = int(rec.get("word_count", 0))
        if seen.get(url, -1) < count:
            seen[url] = count
            if count > best_count:
                best_count = count
                best_url = url
    return best_url, best_count


def q3_top50_words(
    word_freq: dict[str, int],
    stop_words: set[str],
    n: int = 50,
) -> list[tuple[str, int]]:
    """
    Q3 – Top-50 most common words across all crawled pages, ignoring stop words.
    Returns a list of (word, frequency) sorted descending by frequency.
    """
    filtered = {
        word: freq
        for word, freq in word_freq.items()
        if word.lower() not in stop_words and word.isalpha()
    }
    return sorted(filtered.items(), key=lambda x: x[1], reverse=True)[:n]


def q4_uci_subdomains(unique_urls: set[str]) -> list[tuple[str, int]]:
    """
    Q4 – Subdomains under uci.edu with their unique-page counts.
    Returns a list of (subdomain, count) sorted alphabetically by subdomain.
    """
    subdomain_pages: dict[str, set[str]] = defaultdict(set)
    for url in unique_urls:
        parsed = urlparse(url)
        host = parsed.hostname or ""
        if is_uci_subdomain(host):
            subdomain_pages[host].add(url)
    return sorted(
        ((sub, len(pages)) for sub, pages in subdomain_pages.items()),
        key=lambda x: x[0],
    )


